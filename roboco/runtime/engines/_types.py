"""Structural type for the composed AgentOrchestrator, TYPE_CHECKING-only.

Every ``roboco/runtime/engines/*.py`` mixin holds methods moved verbatim
out of ``AgentOrchestrator``; many reference attributes and methods that
live on a DIFFERENT mixin, or on the core class
itself (declared in ``__init__`` / at class scope). mypy checks each mixin
file against its own declared bases only, so it does not know ``self`` is
ultimately a full ``AgentOrchestrator`` with every sibling mixin composed in.

This Protocol names that full cross-mixin surface (mechanically generated
from mypy's own ``has no attribute`` findings against the fresh split, one
entry per distinct missing name, its real return type -- and staticmethod/
classmethod decorator, where the real definition has one, since the
`AgentOrchestrator.foo(...)` class-qualified call pattern some moved bodies
use needs it -- copied from wherever it is actually defined; an
``*args``/``**kwargs`` stub, not the real parameter list, since only a
call's RETURN type needs to be right here, the real signature stays
enforced by the file that actually defines each one). Each mixin's own
module gives its class a TYPE_CHECKING-only base of this Protocol (see any
mixin's own ``if TYPE_CHECKING:`` block) so every method's implicit ``self``
resolves the whole surface, with ZERO changes to any moved method body.
"""

