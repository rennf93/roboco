@dataclass(frozen=True)
class Fix:
    """Replace ``line[start:end]`` of a map file with ``text``."""

    doc: str
    line_index: int
    start: int
    end: int
    text: str


@dataclass(frozen=True)
class Finding:
    doc: str
    line_index: int
    kind: str
    message: str
    fixes: tuple[Fix, ...] = ()

    @property
    def is_error(self) -> bool:
        return self.kind in ERROR_KINDS

    def render(self) -> str:
        return f"{self.doc}:{self.line_index + 1}: {self.kind}: {self.message}"


