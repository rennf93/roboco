def map_documents(root: Path) -> list[Path]:
    return sorted(
        p for p in (root / MAP_DIR).glob("*.md") if p.name not in GENERATED_MAP_FILES
    )


def requires_map_row(path: str) -> bool:
    """A module or build file the map must name (see the module docstring)."""
    name = path.rsplit("/", 1)[-1]
    if path.startswith("roboco/"):
        return name.endswith(".py") and name != "__init__.py"
    return path.startswith(MAPPED_TREES) and name.lower() != "readme.md"


def check_map(root: Path) -> list[Finding]:
    tree = Tree.load(root)
    findings: list[Finding] = []
    mapped_by: dict[str, set[str]] = {}
    for path in map_documents(root):
        doc = path.relative_to(root).as_posix()
        check = MapCheck(tree, doc, path.read_text().splitlines())
        findings.extend(check.run())
        mapped_by[doc] = check.mapped
    findings.extend(unmapped_module_findings(tree, mapped_by))
    return findings


def unmapped_module_findings(
    tree: Tree, mapped_by: dict[str, set[str]]
) -> list[Finding]:
    mapped = set().union(*mapped_by.values())
    return [
        _unmapped_module(path, _owning_slice(path, mapped_by))
        for path in sorted(tree.files)
        if requires_map_row(path) and path not in mapped
    ]


def _owning_slice(path: str, mapped_by: dict[str, set[str]]) -> str | None:
    """The slice mapping the most files of the nearest directory that has any.

    Only a directory's own files count, not its subdirectories', so a big
    package's owner does not claim every file below it.
    """
    directory = path.rsplit("/", 1)[0]
    while directory:
        counts = {
            doc: sum(1 for f in files if f.rpartition("/")[0] == directory)
            for doc, files in mapped_by.items()
            if doc != FRONT_MATTER
        }
        best = max(counts, key=lambda doc: (counts[doc], doc), default=None)
        if best is not None and counts[best]:
            return best
        directory = directory.rpartition("/")[0]
    return None


def _unmapped_module(path: str, owner: str | None) -> Finding:
    where = (
        f"its neighbours are mapped in `{owner}`, so add it to that slice's "
        "Files table (Path | Role | LOC)"
        if owner
        else "add it to the Files table of the slice that owns its subsystem "
        f"(the slice list is in `{FRONT_MATTER}`), or start a new slice"
    )
    return Finding(
        owner or FRONT_MATTER,
        0,
        "unmapped-module",
        f"`{path}` is named by no docs/map table: {where}, then run `make map`",
    )


def apply_fixes(root: Path, findings: list[Finding]) -> int:
    """Rewrite every fixable finding in place; returns how many lines changed."""
    by_line: dict[tuple[str, int], set[Fix]] = defaultdict(set)
    for finding in findings:
        for fix in finding.fixes:
            by_line[fix.doc, fix.line_index].add(fix)
    by_doc: dict[str, dict[int, set[Fix]]] = defaultdict(dict)
    for (doc, index), fixes in by_line.items():
        by_doc[doc][index] = fixes
    changed = 0
    for doc, line_fixes in by_doc.items():
        path = root / doc
        text = path.read_text()
        lines = text.splitlines(keepends=True)
        for index, fixes in line_fixes.items():
            line = lines[index]
            for fix in sorted(fixes, key=lambda f: f.start, reverse=True):
                line = line[: fix.start] + fix.text + line[fix.end :]
            changed += line != lines[index]
            lines[index] = line
        path.write_text("".join(lines))
    return changed


def summarize(findings: list[Finding]) -> str:
    errors = Counter(f.kind for f in findings if f.is_error)
    warnings = Counter(f.kind for f in findings if not f.is_error)

    def _counts(counter: Counter[str]) -> str:
        return ", ".join(f"{kind} {n}" for kind, n in sorted(counter.items())) or "none"

    fixable = sum(1 for f in findings if f.fixes)
    hint = (
        f" {fixable} fixable: `make map` (verify_codebase_map.py --fix) rewrites them."
        if fixable
        else ""
    )
    return (
        f"docs/map: {sum(errors.values())} errors ({_counts(errors)}); "
        f"{sum(warnings.values())} warnings ({_counts(warnings)}).{hint}"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--fix", action="store_true", help="rewrite derivable drift in place"
    )
    parser.add_argument(
        "--verbose", action="store_true", help="also list fixable drift"
    )
    parser.add_argument("--root", type=Path, default=ROOT, help="repository root")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    findings = check_map(root)
    if args.fix:
        changed = apply_fixes(root, findings)
        print(f"rewrote {changed} map lines")
        findings = check_map(root)
    for finding in sorted(
        findings, key=lambda f: (not f.is_error, f.doc, f.line_index)
    ):
        if args.verbose or finding.is_error or not finding.fixes:
            print(finding.render())
    print(summarize(findings))
    return 1 if any(f.is_error for f in findings) else 0


if __name__ == "__main__":
    raise SystemExit(main())
