@dataclass(frozen=True)
class Cell:
    text: str
    start: int


@dataclass(frozen=True)
class Row:
    line_index: int
    header: tuple[str, ...]
    cells: tuple[Cell, ...]

    def cell(self, column: str) -> Cell | None:
        if column not in self.header:
            return None
        index = self.header.index(column)
        return self.cells[index] if index < len(self.cells) else None


def split_cells(line: str) -> tuple[Cell, ...]:
    """Split a table line on its unescaped pipes, keeping each cell's offset."""
    bounds = [
        i for i, ch in enumerate(line) if ch == "|" and (i == 0 or line[i - 1] != "\\")
    ]
    if not line.rstrip().endswith("|"):
        bounds.append(len(line))
    cells = []
    for left, right in itertools.pairwise(bounds):
        raw = line[left + 1 : right]
        leading = len(raw) - len(raw.lstrip())
        cells.append(Cell(raw.strip(), left + 1 + leading))
    return tuple(cells)


def _is_table_start(lines: list[str], index: int) -> bool:
    return (
        lines[index].lstrip().startswith("|")
        and index + 1 < len(lines)
        and _SEPARATOR_ROW.match(lines[index + 1]) is not None
    )


def parse_table_rows(lines: list[str]) -> list[Row]:
    """Every body row of every table outside fenced code blocks."""
    rows: list[Row] = []
    in_fence = False
    header: tuple[str, ...] | None = None
    for index, line in enumerate(lines):
        if _FENCE.match(line):
            in_fence, header = not in_fence, None
            continue
        if in_fence or not line.lstrip().startswith("|"):
            header = None
            continue
        if header is None:
            if _is_table_start(lines, index):
                header = tuple(c.text.lower() for c in split_cells(line))
            continue
        if _SEPARATOR_ROW.match(line):
            continue
        rows.append(Row(index, header, split_cells(line)))
    return rows


