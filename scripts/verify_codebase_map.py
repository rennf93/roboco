@dataclass(frozen=True)
class LineItem:
    """One cited line (or ``start-end`` range) and where its digits sit."""

    start: int
    end: int | None
    approximate: bool
    start_span: tuple[int, int]
    end_span: tuple[int, int] | None


@dataclass
class Reference:
    path: str
    items: list[LineItem] = field(default_factory=list)


def _parse_line_items(text: str, offset: int) -> list[LineItem]:
    items = []
    for match in _LINE_ITEM_PARTS.finditer(text):
        end = match.group("end")
        approx_start = match.start("approx") + offset
        items.append(
            LineItem(
                start=int(match.group("start")),
                end=int(end) if end else None,
                approximate=bool(match.group("approx")),
                start_span=(approx_start, match.end("start") + offset),
                end_span=(match.start("end") + offset, match.end("end") + offset)
                if end
                else None,
            )
        )
    return items


def has_known_file_name(path: str) -> bool:
    name = path.rstrip("/").rsplit("/", 1)[-1].lower()
    if name in KNOWN_FILE_NAMES or name.endswith(".dockerfile"):
        return True
    return "." in name and name.rsplit(".", 1)[1] in KNOWN_EXTENSIONS


def is_path_like(path: str, top_level: frozenset[str]) -> bool:
    """A token worth resolving: a known file name, a dir, or a repo-rooted path."""
    if path.startswith("/"):
        return has_known_file_name(path)
    if has_known_file_name(path) or (path.endswith("/") and "/" in path[:-1]):
        return True
    return "/" in path and path.split("/", 1)[0] in top_level


def extract_references(cell: Cell, top_level: frozenset[str]) -> list[Reference]:
    """The path references in a cell, each with the lines it cites."""
    references: list[Reference] = []
    for match in _REFERENCE.finditer(cell.text):
        if match.group("bare"):
            if references:
                bare_start = match.start("bare") + 1
                references[-1].items.extend(
                    _parse_line_items(match.group("bare")[1:], cell.start + bare_start)
                )
            continue
        path = match.group("path")
        if not is_path_like(path, top_level):
            continue
        reference = Reference(path)
        if match.group("lines"):
            reference.items = _parse_line_items(
                match.group("lines"), cell.start + match.start("lines")
            )
        references.append(reference)
    return references


def symbol_names(cell_text: str) -> list[str]:
    """The symbols a Name cell lists, or [] when the cell is prose.

    Prose, an HTTP route (``GET /api/x``) and a file name are not symbols.
    """
    text = _PARENTHETICAL.sub("", cell_text.replace("`", "")).strip()
    if not text or _HTTP_ROUTE.match(text) or not _NAME_LIST.match(text):
        return []
    names = _NAME_SEPARATOR.split(text)
    return [] if any(has_known_file_name(n) for n in names) else names


