#!/usr/bin/env python3
"""Verify docs/map, the agent-facing codebase map, against the tree it maps.

docs/map is auto-indexed into the knowledge base at startup
(``OptimalService.AUTO_INDEX_DIRS``), so RoboCo's agents act on what its
tables say. This reads every table in the per-slice maps and ``_front.md``
and checks the references in them:

* every path a location column names exists (``missing-path``);
* every symbol a row names is defined in the file the row points at
  (``missing-symbol``) and, when the row cites a line, at that line
  (``line-drift``). Python files are read with ``ast``; other files by a
  definition-shaped text match;
* every LOC cell matches the file's line count (``loc-drift``);
* the db-migrations slice states the real Alembic head
  (``migration-range``) and has a row per migration file
  (``unmapped-migration``);
* every module under ``roboco/`` (``*.py`` but ``__init__.py``) and every
  file under ``docker/`` and ``scripts/`` (but a README) is named by some
  table, by its own path or a glob; a directory row does not count, or a
  module dropped into a mapped package would never be noticed
  (``unmapped-module``).

A missing path or symbol, and a module or migration no table maps, fail the
check: those are how the map rotted, and each message says which slice to
add the row to. An ordinary code edit only shifts line numbers and sizes;
failing on that would break every PR that touches a mapped file, so drift is
a warning and ``--fix`` rewrites what is mechanically derivable (line
numbers, LOC, the migration range) in place. Rows for deleted files, new
modules and stale descriptions need a human.

``_complete_map.md`` is generated by ``scripts/rebuild_map_concat.py`` and is
not read here: run that script after ``--fix``.

The report lists every error and every warning a human has to resolve;
fixable drift is only counted, unless ``--verbose``.

Usage:
    python scripts/verify_codebase_map.py            # report; exit 1 on errors
    python scripts/verify_codebase_map.py --fix      # rewrite drift, then report
    python scripts/verify_codebase_map.py --verbose  # also list fixable drift
    python scripts/verify_codebase_map.py --root R   # check the tree at R
"""

