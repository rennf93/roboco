@dataclass
class MapCheck:
    """Checks one map file's tables against the tree."""

    tree: Tree
    doc: str
    lines: list[str]
    findings: list[Finding] = field(default_factory=list)
    scope: frozenset[str] = frozenset()
    mapped: set[str] = field(default_factory=set)

    def run(self) -> list[Finding]:
        rows = parse_table_rows(self.lines)
        self.scope = self._slice_scope(rows)
        for row in rows:
            self._check_row(row)
        if self.doc.endswith("/" + MIGRATIONS_SLICE):
            self._check_migrations(rows)
        return self.findings

    def _report(
        self, row: Row, kind: str, message: str, fixes: tuple[Fix, ...] = ()
    ) -> None:
        self.findings.append(Finding(self.doc, row.line_index, kind, message, fixes))

    def _fix(self, row: Row, span: tuple[int, int], text: str) -> Fix:
        return Fix(self.doc, row.line_index, span[0], span[1], text)

    def _slice_scope(self, rows: list[Row]) -> frozenset[str]:
        """Paths this slice's Files tables list, to settle abbreviated refs."""
        scope: set[str] = set()
        for row in rows:
            cell = row.cell("path") if "role" in row.header else None
            for reference in (
                extract_references(cell, self.tree.top_level) if cell else []
            ):
                scope.update(self.tree.resolve(reference.path))
        return frozenset(scope)

    def _narrow(self, candidates: list[str]) -> list[str]:
        in_scope = [
            c
            for c in candidates
            if any(c == s or c.startswith(s + "/") for s in self.scope)
        ]
        return in_scope or candidates

    # -- rows ---------------------------------------------------------------

    def _location_cells(self, row: Row) -> list[tuple[str, Cell]]:
        cells = []
        for column in LOCATION_COLUMNS:
            if column == "path" and "role" not in row.header:
                continue  # an endpoint table's Path is a URL
            cell = row.cell(column)
            if cell is not None and cell.text:
                cells.append((column, cell))
        return cells

    def _row_names(self, row: Row) -> list[str]:
        kind = row.cell("kind")
        if kind is not None and any(
            k in kind.text.lower() for k in KINDS_WITHOUT_SYMBOL
        ):
            return []
        for column in NAME_COLUMNS:
            cell = row.cell(column)
            if cell is not None:
                return symbol_names(cell.text)
        return []

    def _check_row(self, row: Row) -> None:
        resolved: list[tuple[Reference, list[str], bool]] = []
        for column, cell in self._location_cells(row):
            for reference in extract_references(cell, self.tree.top_level):
                candidates = self._narrow(self.tree.resolve(reference.path))
                if not candidates:
                    self._report(
                        row, "missing-path", f"`{reference.path}` does not exist"
                    )
                    continue
                resolved.append((reference, candidates, column in CALL_SITE_COLUMNS))
                self._record_mapped(candidates)
        names = self._row_names(row)
        if resolved and not names and self._row_hints(row):
            self._check_hints(row, self._row_hints(row), resolved)
        elif resolved:
            self._check_symbols(row, names, resolved)
        self._check_size(row, resolved)

    def _record_mapped(self, candidates: list[str]) -> None:
        """Files a row names: one unambiguous file, or every match of a glob.

        An ambiguous basename maps none of its candidates, and a directory
        maps none of its contents.
        """
        files = [c for c in candidates if c in self.tree.files]
        if len(files) == 1 or len(files) == len(candidates) > 1:
            self.mapped.update(files)

    def _row_hints(self, row: Row) -> list[str]:
        if any(column in row.header for column in NAME_COLUMNS):
            return []
        for column in HINT_COLUMNS:
            cell = row.cell(column)
            if cell is not None:
                quoted = [
                    name
                    for span in _CODE_SPAN.findall(cell.text)
                    for name in _IDENTIFIER.findall(span)
                ]
                shaped = _HINT_IDENTIFIER.findall(cell.text)
                return list(dict.fromkeys(quoted + shaped))
        return []

    def _check_hints(
        self,
        row: Row,
        hints: list[str],
        resolved: list[tuple[Reference, list[str], bool]],
    ) -> None:
        """Check a prose row's line against the functions its prose names.

        A risk or change row has no Name column, so its line is only as good
        as a guess at which identifier it is about. A line inside (or naming)
        one of the functions/classes the prose mentions is right; otherwise
        the nearest such definition is reported as a ``prose-line-drift``
        suggestion, never auto-fixed. Prose naming nothing defined in the
        file is only checked against the file's length.
        """
        for reference, candidates, _ in resolved:
            for item in reference.items:
                self._check_hinted_item(row, hints, item, candidates)

    def _check_hinted_item(
        self, row: Row, hints: list[str], item: LineItem, candidates: list[str]
    ) -> None:
        found = [
            (path, definitions)
            for path in candidates
            for hint in hints
            if (definitions := self._hint_definitions(path, hint))
        ]
        if not found:
            self._check_line_in_range(row, item, candidates)
            return
        low, high = item.start, item.end or item.start
        within = any(
            d.first_line <= high and low <= d.last_line
            for _, definitions in found
            for d in definitions
        )
        if within or self._line_mentions(found[0][0], low, hints):
            return
        path, definitions = found[0]
        target = _nearest_line(item.start, definitions, [])
        self._report(
            row,
            "prose-line-drift",
            f"line {item.start} is outside `{definitions[0].name}` "
            f"(`{path}:{target}`); check the row by hand",
        )

    def _hint_definitions(self, path: str, hint: str) -> list[Definition]:
        source = self.tree.source(path)
        if source is None:
            return []
        return [d for d in source.find_definitions(hint) if d.block]

    def _line_mentions(self, path: str, line: int, hints: list[str]) -> bool:
        source = self.tree.source(path)
        if source is None or not 0 < line <= source.line_count:
            return False
        return any(
            re.search(rf"(?<!\w){re.escape(hint)}(?!\w)", source.lines[line - 1])
            for hint in hints
        )

    def _check_symbols(
        self,
        row: Row,
        names: list[str],
        resolved: list[tuple[Reference, list[str], bool]],
    ) -> None:
        cited = [
            (item, candidates, call_site)
            for reference, candidates, call_site in resolved
            for item in reference.items
        ]
        checked: set[str] = set()
        if names and len(names) == len(cited):
            pairs = list(zip(names, cited, strict=True))
        elif names and len(cited) == 1:
            pairs = [(names[0], cited[0])]
        else:
            pairs = []
            for item, candidates, _ in cited:
                self._check_line_in_range(row, item, candidates)
        for name, (item, candidates, call_site) in pairs:
            # A row that cites a line claims the name is in THAT file.
            if not self._check_anchor(row, name, item, candidates, call_site=call_site):
                self._check_defined(row, name, candidates, call_site=call_site)
            checked.add(name)
        every_file = sorted({c for _, candidates, _ in resolved for c in candidates})
        call_site = any(call for _, _, call in resolved)
        for name in names:
            if name not in checked:
                self._check_defined(row, name, every_file, call_site=call_site)

    def _check_defined(
        self, row: Row, name: str, files: list[str], *, call_site: bool
    ) -> None:
        if not any(any(self._occurrences(f, name, call_site=call_site)) for f in files):
            where = ", ".join(f"`{f}`" for f in files[:3])
            self._report(row, "missing-symbol", f"`{name}` is not defined in {where}")

    def _check_line_in_range(
        self, row: Row, item: LineItem, candidates: list[str]
    ) -> None:
        sources = [
            s for s in (self.tree.source(c) for c in candidates) if s is not None
        ]
        last = max(item.start, item.end or 0)
        if sources and all(last > s.line_count for s in sources):
            self._report(
                row,
                "line-out-of-range",
                f"line {last} is past the end of `{candidates[0]}` "
                f"({sources[0].line_count} lines)",
            )

    def _occurrences(
        self, path: str, name: str, *, call_site: bool = False
    ) -> tuple[list[Definition], list[int]]:
        """Where ``path`` defines ``name``: Python definitions, else lines.

        A call-site column wants any mention. Otherwise Python needs a real
        definition or a string literal (an env read, a registry key); other
        files need a mention, preferring definition-shaped lines.
        """
        source = self.tree.source(path)
        if source is None:
            return [], []
        for alias in _aliases(name):
            if call_site:
                lines = source.text_occurrences(alias)
            else:
                definitions = source.find_definitions(alias)
                if definitions:
                    return definitions, []
                lines = (
                    source.quoted_occurrences(alias)
                    if source.python
                    else source.definition_like_occurrences(
                        alias, source.text_occurrences(alias)
                    )
                    or source.text_occurrences(alias)
                )
            if lines:
                return [], lines
        if name.rsplit(".", 1)[-1] == Path(path).stem:
            return [], [1]  # the row names the module itself
        return [], []

    def _check_anchor(
        self,
        row: Row,
        name: str,
        item: LineItem,
        candidates: list[str],
        *,
        call_site: bool,
    ) -> bool:
        """Check ``name`` sits at ``item``; report drift. False when undefined."""
        best: tuple[int, str, int] | None = None
        for path in candidates:
            definitions, lines = self._occurrences(path, name, call_site=call_site)
            if not definitions and not lines:
                continue
            if _is_anchored(item, definitions, lines) and not item.approximate:
                return True
            target = _nearest_line(item.start, definitions, lines)
            distance = abs(target - item.start)
            if best is None or distance < best[0]:
                best = (distance, path, target)
        if best is None:
            return False
        self._report_line_drift(row, name, item, best[1], best[2])
        return True

    def _report_line_drift(
        self, row: Row, name: str, item: LineItem, path: str, target: int
    ) -> None:
        fixes = [self._fix(row, item.start_span, str(target))]
        if item.end is not None and item.end_span is not None:
            fixes.append(
                self._fix(row, item.end_span, str(item.end + target - item.start))
            )
        cited = f"~{item.start}" if item.approximate else str(item.start)
        self._report(
            row,
            "line-drift",
            f"`{name}` is at `{path}:{target}`, not line {cited}",
            tuple(fixes),
        )

    # -- sizes --------------------------------------------------------------

    def _check_size(
        self, row: Row, resolved: list[tuple[Reference, list[str], bool]]
    ) -> None:
        column = next(
            (
                c
                for c in (*EXACT_SIZE_COLUMNS, *APPROXIMATE_SIZE_COLUMNS)
                if c in row.header
            ),
            None,
        )
        cell = row.cell(column) if column else None
        match = _SIZE_CELL.match(cell.text) if cell else None
        files = {c for _, candidates, _ in resolved for c in candidates}
        if cell is None or match is None or len(files) != 1:
            return
        source = self.tree.source(files.pop())
        if source is None:
            return
        claimed, actual = int(match.group("count")), source.line_count
        approximate = bool(match.group("approx")) or column in APPROXIMATE_SIZE_COLUMNS
        if claimed == actual or (
            approximate and abs(claimed - actual) <= actual * APPROXIMATE_SIZE_TOLERANCE
        ):
            return
        span = (cell.start + match.start("count"), cell.start + match.end("count"))
        self._report(
            row,
            "loc-drift",
            f"claims {match.group('approx')}{claimed} lines, the file has {actual}",
            (self._fix(row, span, str(actual)),),
        )

    # -- migrations ---------------------------------------------------------

    def _check_migrations(self, rows: list[Row]) -> None:
        migrations = sorted(
            p.rsplit("/", 1)[1]
            for p in self.tree.files
            if p.startswith(MIGRATIONS_DIR + "/")
            and p.endswith(".py")
            and _MIGRATION_NUMBER.match(p.rsplit("/", 1)[1])
        )
        if not migrations:
            return
        head = max(m[:3] for m in migrations)
        self._check_chain_range(head, len(migrations))
        mapped = {
            reference.path.rsplit("/", 1)[-1]
            for row in rows
            if "num" in row.header
            for _, cell in self._location_cells(row)
            for reference in extract_references(cell, self.tree.top_level)
        }
        last_row = max((r.line_index for r in rows if "num" in r.header), default=0)
        for migration in migrations:
            if migration not in mapped:
                self.findings.append(
                    Finding(
                        self.doc,
                        last_row,
                        "unmapped-migration",
                        f"`{MIGRATIONS_DIR}/{migration}` has no row: add one to "
                        "this slice's Migration Chain table (Num | File | "
                        "What it adds/changes) and its logical tree",
                    )
                )

    def _check_chain_range(self, head: str, count: int) -> None:
        for index, line in enumerate(self.lines):
            for pattern in (_CHAIN_RANGE, _FILES_RANGE):
                for match in pattern.finditer(line):
                    self._check_range_match(index, match, head, count)

    def _check_range_match(
        self, index: int, match: re.Match[str], head: str, count: int
    ) -> None:
        fixes = []
        if match.group("head") != head:
            fixes.append(Fix(self.doc, index, *match.span("head"), head))
        if "count" in match.groupdict() and match.group("count") != str(count):
            fixes.append(Fix(self.doc, index, *match.span("count"), str(count)))
        if fixes:
            self.findings.append(
                Finding(
                    self.doc,
                    index,
                    "migration-range",
                    f"`{match.group(0)}`, but the chain has {count} files "
                    f"ending at {head}",
                    tuple(fixes),
                )
            )


def _aliases(name: str) -> list[str]:
    """``ROBOCO_FOO`` is the env name of the pydantic setting ``foo``."""
    if _ENV_SETTING.match(name):
        return [name, name.removeprefix("ROBOCO_").lower()]
    return [name]


def _is_anchored(
    item: LineItem, definitions: list[Definition], lines: list[int]
) -> bool:
    low, high = item.start, item.end or item.start
    if definitions:
        return any(d.first_line <= high and low <= d.line for d in definitions)
    return any(low <= n <= high for n in lines)


def _nearest_line(cited: int, definitions: list[Definition], lines: list[int]) -> int:
    candidates = [d.line for d in definitions] or lines
    return min(candidates, key=lambda n: (abs(n - cited), n))


