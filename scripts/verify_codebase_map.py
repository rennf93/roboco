@dataclass(frozen=True)
class Definition:
    """A symbol defined in a source file.

    ``first_line`` includes decorators, ``line`` is the ``def``/``class`` (or
    assignment) line, ``last_line`` ends the body.
    """

    name: str
    first_line: int
    line: int
    last_line: int
    block: bool = False  # a def or class, not an assignment


def _definition_from_node(
    node: ast.AST, scope: tuple[str, ...]
) -> list[tuple[tuple[str, ...], Definition]]:
    if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef):
        first = min([d.lineno for d in node.decorator_list] + [node.lineno])
        last = node.end_lineno or node.lineno
        definition = Definition(node.name, first, node.lineno, last, block=True)
        return [((*scope, node.name), definition)]
    targets: list[ast.expr] = []
    if isinstance(node, ast.Assign):
        targets = list(node.targets)
    elif isinstance(node, ast.AnnAssign | ast.AugAssign):
        targets = [node.target]
    elif isinstance(node, ast.TypeAlias):
        targets = [node.name]
    names = [
        n.id
        for t in targets
        for n in ast.walk(t)
        if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Store)
    ]
    line = getattr(node, "lineno", 0)
    last = getattr(node, "end_lineno", None) or line
    return [((*scope, name), Definition(name, line, line, last)) for name in names]


def _self_attribute_definitions(
    method: ast.FunctionDef | ast.AsyncFunctionDef, scope: tuple[str, ...]
) -> list[tuple[tuple[str, ...], Definition]]:
    found = []
    for node in ast.walk(method):
        if not isinstance(node, ast.Assign | ast.AnnAssign):
            continue
        targets = node.targets if isinstance(node, ast.Assign) else [node.target]
        for target in targets:
            if (
                isinstance(target, ast.Attribute)
                and isinstance(target.value, ast.Name)
                and target.value.id == "self"
            ):
                last = node.end_lineno or node.lineno
                definition = Definition(target.attr, node.lineno, node.lineno, last)
                found.append(((*scope, target.attr), definition))
    return found


def _nested_blocks(node: ast.AST) -> list[ast.stmt]:
    """Statements of an if/try/with/for at the same scope level."""
    block: list[ast.stmt] = []
    for attr in ("body", "orelse", "finalbody"):
        block.extend(getattr(node, attr, []) or [])
    for handler in getattr(node, "handlers", []) or []:
        block.extend(handler.body)
    return block


def python_definitions(tree: ast.Module) -> dict[tuple[str, ...], list[Definition]]:
    """Every module/class-level symbol keyed by its qualified name parts."""
    found: dict[tuple[str, ...], list[Definition]] = defaultdict(list)
    pending: list[tuple[ast.stmt, tuple[str, ...]]] = [(s, ()) for s in tree.body]
    while pending:
        node, scope = pending.pop()
        for key, definition in _definition_from_node(node, scope):
            found[key].append(definition)
        if isinstance(node, ast.ClassDef):
            pending.extend((s, (*scope, node.name)) for s in node.body)
        elif isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef):
            if scope:
                for key, definition in _self_attribute_definitions(node, scope):
                    found[key].append(definition)
            pending.extend(
                (s, (*scope, node.name))
                for s in node.body
                if isinstance(s, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef)
            )
        elif isinstance(node, ast.If | ast.Try | ast.With | ast.For):
            pending.extend((s, scope) for s in _nested_blocks(node))
    return found


def _is_reexport(node: ast.stmt) -> bool:
    if isinstance(node, ast.Import | ast.ImportFrom):
        return True
    return isinstance(node, ast.Assign) and any(
        isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets
    )


def reexport_lines(tree: ast.Module) -> frozenset[int]:
    """Lines of imports and ``__all__``: a name there is not defined there."""
    lines: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.stmt) and _is_reexport(node):
            lines.update(range(node.lineno, (node.end_lineno or node.lineno) + 1))
    return frozenset(lines)


@dataclass
class SourceFile:
    """A file the map points into, read once.

    ``python`` is set when the file parsed as Python: its symbols then come
    from the syntax tree, not from text that merely mentions them.
    """

    lines: list[str]
    definitions: dict[tuple[str, ...], list[Definition]]
    ignored_lines: frozenset[int]
    python: bool

    @classmethod
    def read(cls, path: Path) -> SourceFile:
        text = path.read_text(errors="replace")
        tree = _parse_python(text) if path.suffix in {".py", ".pyi"} else None
        if tree is None:
            return cls(text.splitlines(), {}, frozenset(), python=False)
        return cls(
            text.splitlines(),
            python_definitions(tree),
            reexport_lines(tree),
            python=True,
        )

    @property
    def line_count(self) -> int:
        return len(self.lines)

    def find_definitions(self, name: str) -> list[Definition]:
        """Python definitions matching ``name`` (``Cls.attr`` or a bare name).

        A leading ``module.`` qualifier the file itself doesn't define (e.g.
        ``markers.set_marker``) is dropped one part at a time.
        """
        parts = tuple(name.split("."))
        while parts:
            hits = [
                d
                for key, defs in self.definitions.items()
                if key[-len(parts) :] == parts
                for d in defs
            ]
            if hits:
                return hits
            parts = parts[1:]
        return []

    def text_occurrences(self, name: str) -> list[int]:
        """1-based lines naming ``name`` as a whole word, outside re-exports."""
        word = re.compile(rf"(?<![\w$]){re.escape(name.rsplit('.', 1)[-1])}(?![\w$])")
        return self._lines_matching(word)

    def quoted_occurrences(self, name: str) -> list[int]:
        """Lines carrying ``name`` as a string literal (env reads, registries)."""
        quoted = re.compile(rf"[\"']{re.escape(name.rsplit('.', 1)[-1])}[\"']")
        return self._lines_matching(quoted)

    def _lines_matching(self, pattern: re.Pattern[str]) -> list[int]:
        return [
            i + 1
            for i, line in enumerate(self.lines)
            if i + 1 not in self.ignored_lines and pattern.search(line)
        ]

    def definition_like_occurrences(self, name: str, lines: list[int]) -> list[int]:
        short = re.escape(name.rsplit(".", 1)[-1])
        shape = re.compile(
            rf"\b{_DEFINITION_KEYWORD}\s+(?:\w+\s+)*{short}\b"
            rf"|^\s*['\"]?{short}['\"]?\s*[(:=<?]"
        )
        return [n for n in lines if shape.search(self.lines[n - 1])]


def _parse_python(text: str) -> ast.Module | None:
    try:
        return ast.parse(text)
    except SyntaxError:
        return None


@dataclass
class Tree:
    """The repository the map describes."""

    root: Path
    files: frozenset[str]
    dirs: frozenset[str]
    by_name: dict[str, list[str]]
    top_level: frozenset[str]
    _sources: dict[str, SourceFile | None] = field(default_factory=dict)

    @classmethod
    def load(cls, root: Path) -> Tree:
        files = frozenset(_list_files(root))
        dirs = {
            "/".join(parts[:i])
            for parts in (f.split("/") for f in files)
            for i in range(1, len(parts))
        }
        by_name: dict[str, list[str]] = defaultdict(list)
        for path in files | dirs:
            by_name[path.rsplit("/", 1)[-1]].append(path)
        top_level = frozenset(p.split("/", 1)[0] for p in files)
        return cls(root, files, frozenset(dirs), by_name, top_level)

    def source(self, path: str) -> SourceFile | None:
        if path not in self._sources:
            self._sources[path] = (
                SourceFile.read(self.root / path) if path in self.files else None
            )
        return self._sources[path]

    def resolve(self, reference: str) -> list[str]:
        """Repo paths a (possibly abbreviated or globbed) reference names.

        A reference resolves when every brace expansion of it does; [] means
        it names nothing in the tree.
        """
        if reference.startswith("/"):
            return []
        resolved: list[str] = []
        for pattern in expand_braces(reference.removeprefix("./")):
            matches = self._resolve_one(pattern)
            if not matches:
                return []
            resolved.extend(matches)
        return sorted(set(resolved))

    def _resolve_one(self, pattern: str) -> list[str]:
        bare = pattern.rstrip("/")
        if "*" in bare or "?" in bare:
            return self._glob(bare)
        if bare in self.files or bare in self.dirs:
            return [bare]
        tail = bare.rsplit("/", 1)[-1]
        return [p for p in self.by_name.get(tail, []) if p.endswith("/" + bare)]

    def _glob(self, pattern: str) -> list[str]:
        # Next.js route segments like ``[id]`` are literal brackets, not a set.
        escaped = "".join({"[": "[[]", "]": "[]]"}.get(ch, ch) for ch in pattern)
        return [
            p
            for p in self.files | self.dirs
            if fnmatch.fnmatchcase(p, escaped) or fnmatch.fnmatchcase(p, "*/" + escaped)
        ]


def expand_braces(pattern: str) -> list[str]:
    match = _BRACES.search(pattern)
    if match is None:
        return [pattern]
    head, tail = pattern[: match.start()], pattern[match.end() :]
    return [
        expanded
        for option in match.group(1).split(",")
        for expanded in expand_braces(head + option + tail)
    ]


def _list_files(root: Path) -> list[str]:
    """Tracked + untracked-but-not-ignored files; a plain walk outside git."""
    try:
        listed = subprocess.run(
            [
                "git",
                "-C",
                str(root),
                "ls-files",
                "-z",
                "--cached",
                "--others",
                "--exclude-standard",
            ],
            capture_output=True,
            check=True,
        ).stdout.decode()
    except (OSError, subprocess.CalledProcessError):
        listed = ""
    if listed:
        return [p for p in listed.split("\0") if p and (root / p).is_file()]
    return [
        p.relative_to(root).as_posix()
        for p in root.rglob("*")
        if p.is_file() and not SKIPPED_DIRS.intersection(p.relative_to(root).parts)
    ]


